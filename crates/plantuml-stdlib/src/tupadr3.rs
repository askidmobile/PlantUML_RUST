use std::collections::HashMap;

/// Регистрирует tupadr3 включения
pub fn register(registry: &mut HashMap<&'static str, &'static str>) {
    // Common
    registry.insert("tupadr3/common", TUPADR3_COMMON);
    registry.insert("tupadr3/common.puml", TUPADR3_COMMON);

    // DevIcons
    registry.insert("tupadr3/devicons/react", DEVICON_REACT);
    registry.insert("tupadr3/devicons/angular", DEVICON_ANGULAR);
    registry.insert("tupadr3/devicons/vue", DEVICON_VUE);
    registry.insert("tupadr3/devicons/nodejs", DEVICON_NODEJS);
    registry.insert("tupadr3/devicons/mongodb", DEVICON_MONGODB);
    registry.insert("tupadr3/devicons/mysql", DEVICON_MYSQL);

    // Font Awesome
    registry.insert("tupadr3/font-awesome/server", FA_SERVER);
    registry.insert("tupadr3/font-awesome/database", FA_DATABASE);
    registry.insert("tupadr3/font-awesome/cloud", FA_CLOUD);
    registry.insert("tupadr3/font-awesome/users", FA_USERS);
    registry.insert("tupadr3/font-awesome/cog", FA_COG);
    registry.insert("tupadr3/font-awesome/lock", FA_LOCK);
}

