//! Спрайты и макросы для создания диаграмм с Office элементами.

use std::collections::HashMap;

/// Регистрирует Office включения
pub fn register(registry: &mut HashMap<&'static str, &'static str>) {
    // Common
    registry.insert("office/common", OFFICE_COMMON);
    registry.insert("office/common.puml", OFFICE_COMMON);

    // Servers
    registry.insert("office/Servers/application_server", OFFICE_APP_SERVER);
    registry.insert("office/Servers/database_server", OFFICE_DB_SERVER);
    registry.insert("office/Servers/web_server", OFFICE_WEB_SERVER);

    // Users
    registry.insert("office/Users/user", OFFICE_USER);
    registry.insert("office/Users/admin", OFFICE_ADMIN);

    // Concepts
    registry.insert("office/Concepts/globe", OFFICE_GLOBE);
    registry.insert("office/Concepts/firewall", OFFICE_FIREWALL);
}

